-- ============================================================================
-- IoT-Based Health Monitoring System
-- Database Schema Definition (DDL) for Oracle Database
-- Compatible with Oracle 12c, 18c, 19c, 21c, and 23c/26ai
-- SQL*Plus / Oracle SQL Developer compatible
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. DROP EXISTING OBJECTS (Safe cleanup for repeated runs)
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE HEALTH_READINGS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PATIENTS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE USERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

-- ----------------------------------------------------------------------------
-- 2. TABLE: USERS (Authentication & Role Management)
-- Stores credentials with secure SHA-256 password hashes
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME        VARCHAR2(50) NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    PASSWORD_HASH   VARCHAR2(256) NOT NULL,
    ROLE            VARCHAR2(30) DEFAULT 'Staff Nurse' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('Administrator', 'Doctor', 'Staff Nurse', 'Lab Technician'))
);

-- ----------------------------------------------------------------------------
-- 3. TABLE: PATIENTS (Healthcare In-patient Registry)
-- ----------------------------------------------------------------------------
CREATE TABLE PATIENTS (
    PATIENT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME       VARCHAR2(100) NOT NULL,
    AGE             NUMBER(3) NOT NULL,
    GENDER          VARCHAR2(10) NOT NULL,
    CONTACT_NUMBER  VARCHAR2(20) NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    BLOOD_GROUP     VARCHAR2(5) NOT NULL,
    MEDICAL_HISTORY VARCHAR2(500),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_PATIENTS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_PATIENTS_AGE CHECK (AGE > 0 AND AGE <= 125),
    CONSTRAINT CHK_PATIENTS_GENDER CHECK (GENDER IN ('Male', 'Female', 'Other')),
    CONSTRAINT CHK_PATIENTS_BLOOD CHECK (BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'))
);

-- ----------------------------------------------------------------------------
-- 4. TABLE: HEALTH_READINGS (Simulated IoT Telemetry Streams)
-- Stores continuous vitals with calculated clinical severity triage
-- ----------------------------------------------------------------------------
CREATE TABLE HEALTH_READINGS (
    READING_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATIENT_ID          NUMBER NOT NULL,
    TEMPERATURE         NUMBER(4, 1) NOT NULL,  -- Body temperature in Celsius (°C)
    HEART_RATE          NUMBER(3) NOT NULL,     -- Pulse in Beats Per Minute (BPM)
    SPO2                NUMBER(5, 2) NOT NULL,  -- Blood Oxygen Saturation (%)
    SYSTOLIC_BP         NUMBER(3) NOT NULL,     -- Systolic Blood Pressure (mmHg)
    DIASTOLIC_BP        NUMBER(3) NOT NULL,     -- Diastolic Blood Pressure (mmHg)
    RESPIRATORY_RATE    NUMBER(3) NOT NULL,     -- Breaths per minute (BPM)
    OVERALL_STATUS      VARCHAR2(20) NOT NULL,  -- NORMAL, WARNING, CRITICAL
    RECORDED_AT         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    SOURCE_TYPE         VARCHAR2(50) DEFAULT 'SIMULATED_IOT_TELEMETRY' NOT NULL,
    CONSTRAINT FK_READINGS_PATIENT FOREIGN KEY (PATIENT_ID) 
        REFERENCES PATIENTS(PATIENT_ID) 
        ON DELETE CASCADE,
    CONSTRAINT CHK_READING_TEMP CHECK (TEMPERATURE >= 30.0 AND TEMPERATURE <= 45.0),
    CONSTRAINT CHK_READING_HR CHECK (HEART_RATE >= 30 AND HEART_RATE <= 250),
    CONSTRAINT CHK_READING_SPO2 CHECK (SPO2 >= 50.0 AND SPO2 <= 100.0),
    CONSTRAINT CHK_READING_SYS CHECK (SYSTOLIC_BP >= 50 AND SYSTOLIC_BP <= 260),
    CONSTRAINT CHK_READING_DIA CHECK (DIASTOLIC_BP >= 30 AND DIASTOLIC_BP <= 160),
    CONSTRAINT CHK_READING_RESP CHECK (RESPIRATORY_RATE >= 5 AND RESPIRATORY_RATE <= 60),
    CONSTRAINT CHK_READING_STATUS CHECK (OVERALL_STATUS IN ('NORMAL', 'WARNING', 'CRITICAL'))
);

-- ----------------------------------------------------------------------------
-- 5. PERFORMANCE INDEXES
-- Optimizes patient search and time-series telemetry querying
-- ----------------------------------------------------------------------------
CREATE INDEX IDX_PATIENTS_NAME ON PATIENTS(FULL_NAME);
CREATE INDEX IDX_READINGS_PATIENT ON HEALTH_READINGS(PATIENT_ID);
CREATE INDEX IDX_READINGS_RECORDED ON HEALTH_READINGS(RECORDED_AT DESC);
CREATE INDEX IDX_READINGS_STATUS ON HEALTH_READINGS(OVERALL_STATUS);

COMMIT;
